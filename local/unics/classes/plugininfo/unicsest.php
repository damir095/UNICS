<?php
namespace local_unics\plugininfo;

use core\plugininfo\base;

defined('MOODLE_INTERNAL') || die();

/**
 * Метаданные типа подплагинов unicsest (оценщики владения навыком).
 *
 * Moodle требует такой класс для КАЖДОГО объявленного типа подплагинов: без него
 * plugin_manager пишет «Subplugin type "unicsest" should define class ...» на каждое
 * обращение к списку плагинов. Поймано сьютом сразу после объявления типа.
 *
 * Включение/выключение отдельных подплагинов НЕ поддерживаем: активный оценщик ровно
 * один и выбирается настройкой local_unics/mastery_estimator, а не флагом у каждого
 * подплагина. Два одновременно включенных оценщика не имеют смысла - владение считается
 * одним способом, иначе значения в unics_skill_mastery несопоставимы между собой.
 */
class unicsest extends base {

    /**
     * Удаление подплагина через интерфейс управления плагинами разрешено: это и есть
     * смысл точки расширения - оценщик ставится и снимается папкой. Ядро при снятии
     * молча возвращается на встроенный расчет (см. estimator_factory::make).
     */
    public function is_uninstall_allowed() {
        return true;
    }
}
