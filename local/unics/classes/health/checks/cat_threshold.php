<?php
namespace local_unics\health\checks;

use local_unics\adaptive\estimate_precision;
use local_unics\health\check;
use local_unics\health\check_result;
use local_unics\learning\cat_session_manager;

defined('MOODLE_INTERNAL') || die();

/**
 * Может ли настроенный порог точности CAT сработать ХОТЬ КОГДА-НИБУДЬ.
 *
 * Замер 2026-09-08 ([[cat-attainable-precision]]): порог 0.3, стоявший на стенде, не сработал ни
 * разу. Четыреста смоделированных сессий из четырехсот остановились по пределу заданий, живые
 * сессии стенда - по исчерпанию пула, набрав 3-5 заданий и закончившись с ошибкой 0.75-0.97.
 *
 * ВОПРОС ЗДЕСЬ О НАСТРОЙКАХ, А НЕ О БАЗЕ. Первая редакция искала самый богатый пул установки, и
 * ревью показало сразу две беды: пул считался не оттуда, откуда его берет сам CAT (тот идет по
 * привязкам с поддеревом, а не по одному element_id в таблице параметров), и совет «наберите N
 * заданий» был арифметически невыполним - предел заданий за сессию режет пул раньше, чем он
 * наберется. Проверено на стенде: мой счет давал 4 при настоящих 11, а обещанный 41 при пределе
 * 20 дает 0.408, а не 0.30.
 *
 * Отсюда правильная постановка: точность ограничена НЕ размером банка, а числом заданий, которое
 * ребенок успевает получить. Больше предела ему не дадут, сколько заданий ни накопи. Значит
 * достижимый минимум ошибки считается из одного предела, никакая выборка не нужна, и ответ верен
 * для любой установки.
 */
class cat_threshold implements check {

    /**
     * Информация задания Раша, попавшего точно в способность: a^2 * p * (1-p) при a = 1, p = 0.5.
     *
     * ДОПУЩЕНИЕ, и его надо называть: у заданий с оцененной дискриминацией a может быть больше
     * единицы, и тогда пол ошибки ниже. Но оценка дискриминации включается только с
     * item_irt_manager::MIN_N_FOR_2PL наблюдений на задание, а этот порог измерен и высок, так что
     * на практике вся выборка идет с a = 1. Где это перестанет быть правдой, проверка станет
     * ПЕССИМИСТИЧНОЙ - предупредит там, где порог уже достижим; поэтому в тексте сказано «при
     * пределе в N заданий», а не «недостижим никогда».
     */
    private const ITEM_INFO_RASCH = 0.25;

    public function name(): string {
        return 'cat_threshold';
    }

    public function title(): string {
        return 'Порог точности адаптивной проверки';
    }

    /** Ни одного запроса: считается из двух настроек. */
    public function is_cheap(): bool {
        return true;
    }

    public function run(): check_result {
        if ((int)get_config('local_unics', 'adaptive_cat_enabled') !== 1) {
            return check_result::ok('Адаптивная проверка выключена');
        }

        $threshold = estimate_precision::threshold();
        $maxitems = (int)get_config('local_unics', 'cat_max_items');
        if ($maxitems <= 0) {
            $maxitems = cat_session_manager::DEFAULT_MAX_ITEMS;
        }

        // Априор N(0,1) дает единицу информации, каждое задание добавляет ITEM_INFO_RASCH.
        $floor = 1.0 / sqrt(1.0 + self::ITEM_INFO_RASCH * $maxitems);

        // Сравнение строгое в пользу тревоги: сервис останавливается по «se СТРОГО меньше порога»,
        // значит ровно на поле точность не достигнута и остановки не будет
        // (estimate_precision::is_provisional держит ту же границу).
        if ($floor < $threshold) {
            return check_result::ok('Достижим: при пределе в ' . $maxitems
                . ' заданий точность доходит до ' . format_float($floor, 3)
                . ' при пороге ' . format_float($threshold, 2));
        }

        // Сколько заданий за сессию нужно для этого порога: SE = 1/sqrt(1 + n/4).
        $needitems = (int)ceil((1.0 / ($threshold * $threshold) - 1.0) / self::ITEM_INFO_RASCH);
        // lib.php грузится НЕ везде: проверка дешевая и считается на каждой штабной странице, а
        // зовется и из CLI. Без этой строки склонение уронило бы страницу «undefined function».
        global $CFG;
        require_once($CFG->dirroot . '/local/unics/lib.php');

        return check_result::attention(
            'Порог ' . format_float($threshold, 2) . ' недостижим: при пределе в '
                . $maxitems . ' заданий точнее ' . format_float($floor, 3) . ' не будет',
            'Ни одна проверка не остановится по достигнутой точности - все дойдут до предела и '
            . 'будут помечены как предварительные. Накопить больше заданий не поможет: ребенку все '
            . 'равно дадут не больше предела. Либо поднимите порог до ' . format_float($floor, 2)
            . ', либо увеличьте предел заданий за сессию примерно до ' . $needitems . ' '
            . local_unics_plural($needitems, 'задания', 'заданий', 'заданий') . '.',
            [
                'Порог точности' => format_float($threshold, 2),
                'Предел заданий за сессию' => $maxitems,
                'Достижимая точность' => format_float($floor, 3),
            ]
        );
    }
}
