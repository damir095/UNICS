<?php
namespace local_unics\learning;

defined('MOODLE_INTERNAL') || die();

/**
 * Пределы одной адаптивной проверки: сколько заданий ребенок может получить.
 *
 * Отдельным классом, а не константами в cat_session_manager, по двум причинам.
 *
 * Первая: одно и то же число подставляют ЧЕТЫРЕ места - сам оркестратор, индикатор готовности,
 * проверка здоровья и описание настройки, - и копии уже расходились (найдено ревью дважды).
 * Считать достижимую точность по одному пределу, а вести сессию по другому значит обещать
 * методисту не то, что произойдет.
 *
 * Вторая: cat_session_manager на уровне файла тянет question/engine/lib.php, то есть весь движок
 * вопросов Moodle. Проверка здоровья дешевая и идет на КАЖДОЙ штабной странице, описание
 * настройки - на странице администратора; движок не нужен ни там, ни там, а ссылка на константу
 * оркестратора загружала его целиком (найдено ревью).
 */
class cat_limits {

    /** Запасные пределы, если настройки не заданы. */
    public const DEFAULT_MAX_ITEMS = 20;
    public const DEFAULT_MIN_ITEMS = 5;

    /**
     * Предел заданий за сессию. Именно он ограничивает достижимую точность: больше предела
     * ребенку не дадут, сколько заданий ни накопи ([[cat-attainable-precision]]).
     */
    public static function max_items(): int {
        $max = (int)get_config('local_unics', 'cat_max_items');
        return $max > 0 ? $max : self::DEFAULT_MAX_ITEMS;
    }

    /** Минимум заданий до возможной остановки по достигнутой точности. */
    public static function min_items(): int {
        $min = (int)get_config('local_unics', 'cat_min_items');
        return $min > 0 ? $min : self::DEFAULT_MIN_ITEMS;
    }
}
