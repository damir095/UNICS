<?php
namespace local_unics\ai;

defined('MOODLE_INTERNAL') || die();

/**
 * Распознавание отказа модели ([[ai-refusal-detector-design]]).
 *
 * Зачем: 2026-08-09 GigaChat вернул на теме «Круговорот воды в природе» цензурную
 * болванку вместо учебного текста, она легла в курс страницей материала, а УМК
 * получил статус «готов». Ребенок с ОВЗ получил бы мусор вместо урока, и увидеть
 * это можно было только глазами.
 *
 * Класс чистый: ни сети, ни БД.
 *
 * @package local_unics
 */
class refusal_detector {

    /** finish_reason, которым GigaChat помечает сработавший фильтр. Замерено трижды. */
    public const BLACKLIST = 'blacklist';

    /**
     * Потолок длины, до которого ответ вообще может быть болванкой отказа.
     *
     * Замеры 2026-08-09: blacklist-ная болванка - 336 символов, мягкая - 367. Самый
     * короткий законный учебный материал на стенде - 1793 символа, а категория
     * «длительное лечение» заказывает 250-350 СЛОВ, то есть от 1700 символов. Порог
     * посередине с большим запасом в обе стороны.
     *
     * Длина НЕ является самостоятельным признаком отказа - только ограничителем для
     * поиска фраз (см. MARKERS).
     */
    public const MAX_REFUSAL_LEN = 600;

    /**
     * Фразы-болванки отказа.
     *
     * Нужны сверх finish_reason, потому что отказов ДВА вида: blacklist-ный (ровно 336
     * символов, воспроизводится надежно) и мягкий - тот, что реально лег в курс. Мягкий
     * не воспроизвелся ни разу за семь живых прогонов, и его finish_reason неизвестен.
     *
     * Ищутся ТОЛЬКО в коротком ответе (MAX_REFUSAL_LEN). Без этого ограничения законный
     * урок про искусственный интеллект («программа не обладает собственным мнением»)
     * объявлялся отказом и убивался - воспроизведено на лекции в 2059 символов.
     *
     * Пополняется правкой этой константы.
     */
    private const MARKERS = [
        'не обладает собственным мнением',
        'связанные с чувствительными темами',
        'временно ограничены',
    ];

    /**
     * Какой сигнал опознал отказ, или null если это не отказ.
     *
     * Отдельно от is_refusal(), потому что для разбора мало факта: пачка отказов и
     * блокировка конкретной темы выглядят одинаково, пока не видно, сработало поле
     * finish_reason или совпадение фразы ([[ai-refusal-trace-design]], раздел 1.2).
     *
     * @param string $text сырой ответ модели, ДО output_style::clean()
     * @param string $finish_reason поле ответа; пустая строка = неизвестен
     */
    public static function reason_for(string $text, string $finish_reason): ?string {
        if ($finish_reason === self::BLACKLIST) {
            return 'finish_reason=' . self::BLACKLIST;
        }

        // Пустой ответ ловит проверка длины в generate_text_gigachat() - не дублируем.
        $trimmed = trim($text);
        if ($trimmed === '') {
            return null;
        }

        // Полноразмерный материал болванкой быть не может: искать в нем фразы - значит
        // убивать законные уроки, где фраза встречается по делу.
        if (\core_text::strlen($trimmed) > self::MAX_REFUSAL_LEN) {
            return null;
        }

        foreach (self::MARKERS as $marker) {
            if (mb_stripos($text, $marker) !== false) {
                return 'фраза «' . $marker . '»';
            }
        }

        return null;
    }

    /** Факт отказа. Тонкая обертка: вся логика живет в reason_for(). */
    public static function is_refusal(string $text, string $finish_reason): bool {
        return self::reason_for($text, $finish_reason) !== null;
    }
}
