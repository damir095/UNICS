/**
 * Формальные признаки брака в задании ([[answer-judge-design]], раздел 2.1).
 *
 * Ярус не знает предмета и не обращается к сети: он ловит то, что видно по самой разметке
 * задания, и потому работает на любом предмете, где арифметический верификатор молчит.
 *
 * Разделение на «явный брак» и «подозрение» принципиально: по корреляционному признаку
 * выкашивать годные задания дороже, чем терпеть их. Подозрения уезжают в след и никогда
 * не меняют вердикт.
 *
 * @package local_unics
 */
class question_sanity {

    /** Во сколько раз ключ должен быть длиннее САМОГО ДЛИННОГО дистрактора для подозрения. */
    private const LONG_KEY_RATIO = 2.0;

    /**
     * Отрицания в формулировке вопроса.
     *
     * Список намеренно шире одного «не»: «кроме» и «исключением» - то же самое отрицание,
     * выраженное иначе, и детям с ЗПР дается так же тяжело. Родственный список живет в
     * arithmetic_checker::NEGATIONS, но служит другому: там он ЗАПРЕЩАЕТ вердикт, здесь
     * лишь помечает вопрос для следа, поэтому классы не связаны.
     */
    private const NEGATION = '~(^|\s)не\s|неверн|не верн|ошибочн|ложн|(^|\s)кроме(\s|$)|исключен~u';

    /**
     * Вопрос требует НЕСКОЛЬКИХ ответов, а выбрать можно один.
     *
     * Живой заход 2026-08-23: «Какие два материка полностью расположены в южном полушарии?» с
     * одним верным вариантом. Ребенок, понимающий тему, ответить верно не может физически.
     *
     * Числительное обязательно («какие два», «три органоида»): голое множественное число -
     * законная форма вопроса с одним ответом («какие органоиды отвечают за фотосинтез»).
     */
    private const MULTI_ANSWER = '~(^|\s)(выберите|укажите|отметьте|назовите)\s+все(\s|$)'
        . '|(^|\s)перечислите(\s|$)'
        . '|(^|\s)(два|две|три|четыре|пять)\s~u';

    /** Длина вопроса, после которой формулировка тяжела для ребенка с ЗПР. */
    private const LONG_QUESTION = 150;

    /**
     * Нормализация для сравнения вариантов: пробелы, регистр, конечная точка.
     *
     * Кириллица - только через mb_*: strtolower ее не берет и два одинаковых варианта,
     * различающихся регистром, разошлись бы.
     */
    public static function normalize(string $s): string {
        // На битом UTF-8 preg_replace возвращает null: без страховки дальше уходил null в
        // mb_strtolower, и испорченный байтами вариант объявлялся ПУСТЫМ - вопрос выбывал
        // с неверной причиной. Тот же прием стоит в arithmetic_checker.
        $s = preg_replace('~\s+~u', ' ', trim($s)) ?? trim($s);
        $s = mb_strtolower($s);
        // Только точка и пробел: rtrim режет ПОБАЙТНО, и байт 0xA0 из списка обрубал бы
        // многобайтные символы, кончающиеся на него (эмодзи U+1F420, крестик U+2020),
        // оставляя невалидный UTF-8. Неразрывный пробел уже свернут в обычный выше.
        return rtrim($s, '. ');
    }

    /**
     * Вердикт по формальным признакам.
     *
     * @param string $text текст вопроса
     * @param array $answers варианты ответа
     * @param int $correct индекс ключа
     * @return array ['verdict' => 'ok'|'drop', 'reason' => string, 'notes' => string[]]
     */
    public static function verdict(string $text, array $answers, int $correct): array {
        $answers = array_values($answers);
        $n = count($answers);
        $notes = [];

        if ($n < 2) {
            return self::drop('вариантов меньше двух');
        }
        if (self::normalize($text) === '') {
            // Вопрос без текста - тот же класс поломки разметки, что и пустой вариант.
            // Генератор такое отсеивает своей проверкой, но судья ее не делает.
            return self::drop('пустой текст вопроса');
        }
        if ($correct < 0 || $correct >= $n) {
            // Зажим индекса прятал ошибку: correct = 7 при четырех вариантах объявлял верным
            // последний, и ребенок получал «неверно» за верный ответ. Битый индекс означает,
            // что модель потеряла соответствие ключа вариантам, - доверять тут нечему.
            return self::drop('индекс ключа вне диапазона');
        }

        $norm = [];
        foreach ($answers as $a) {
            $one = self::normalize((string)$a);
            if ($one === '') {
                return self::drop('пустой вариант ответа');
            }
            $norm[] = $one;
        }
        if (count(array_unique($norm)) !== $n) {
            return self::drop('два варианта одинаковы');
        }
        $qnorm = self::normalize($text);
        if (in_array($qnorm, $norm, true)) {
            return self::drop('вариант повторяет текст вопроса');
        }
        if (preg_match(self::MULTI_ANSWER, $qnorm)) {
            return self::drop('вопрос требует несколько ответов, а выбрать можно один');
        }
        // Вариант, целиком входящий в другой, делает выбор неоднозначным: ребенок, знающий
        // ответ «Москва», не может решить между «Москва» и «Москва и область». Сравниваем ПО
        // СЛОВАМ, иначе «Рим» оказался бы вложен в «Кримпель».
        foreach ($norm as $i => $a) {
            foreach ($norm as $j => $b) {
                if ($i !== $j && self::contains_words($b, $a)) {
                    return self::drop('один вариант входит в другой');
                }
            }
        }

        // Ниже - только подозрения: вердикт они не меняют.
        // Меряем по нормализованным строкам и против САМОГО ДЛИННОГО дистрактора, а не против
        // среднего: один многословный неверный вариант поднимал среднее и прятал ключ, который
        // вдвое длиннее всех остальных, - то есть ровно ту утечку подсказки, ради которой
        // признак заведен.
        $keylen = mb_strlen($norm[$correct]);
        $longest = 0;
        foreach ($norm as $i => $one) {
            if ($i !== $correct) {
                $longest = max($longest, mb_strlen($one));
            }
        }
        if ($keylen >= $longest * self::LONG_KEY_RATIO) {
            $notes[] = 'ключ заметно длиннее прочих вариантов';
        }
        foreach ($norm as $one) {
            if (preg_match('~все перечислен|все ответы верн|все варианты верн~u', $one)) {
                $notes[] = 'среди вариантов «все перечисленное»';
                break;
            }
        }
        // Отрицание детям с ЗПР дается тяжело, но само по себе задание не портит.
        $lower = mb_strtolower($text);
        if (preg_match(self::NEGATION, $lower)) {
            $notes[] = 'отрицание в формулировке';
        }
        // Двойное отрицание разбирать тяжело всем, а ребенку с ЗПР - вдвойне.
        if (preg_match_all('~(^|\s)не\s~u', $lower) > 1) {
            $notes[] = 'двойное отрицание';
        }
        if (mb_strlen(trim($text)) > self::LONG_QUESTION) {
            $notes[] = 'вопрос длинный - тяжело для ЗПР';
        }
        // Несколько предложений в вопросе: ребенку приходится удерживать в голове условие и
        // сам вопрос одновременно.
        if (preg_match_all('~[.!?]\s+\p{Lu}~u', trim($text)) > 0) {
            $notes[] = 'вопрос из нескольких предложений';
        }

        return ['verdict' => 'ok', 'reason' => '', 'notes' => $notes];
    }

    /**
     * Входит ли строка $needle в $haystack как ЦЕЛЫЕ слова подряд.
     *
     * По подстроке сравнивать нельзя: «Рим» оказался бы вложен в «Кримпель», и годное задание
     * выбывало бы за неоднозначность, которой нет.
     */
    private static function contains_words(string $haystack, string $needle): bool {
        if ($needle === '' || $haystack === $needle) {
            return false;
        }
        $hw = preg_split('~\s+~u', $haystack) ?: [];
        $nw = preg_split('~\s+~u', $needle) ?: [];
        $n = count($nw);
        if ($n === 0 || $n > count($hw)) {
            return false;
        }
        for ($i = 0; $i + $n <= count($hw); $i++) {
            if (array_slice($hw, $i, $n) === $nw) {
                return true;
            }
        }
        return false;
    }

    private static function drop(string $reason): array {
        return ['verdict' => 'drop', 'reason' => $reason, 'notes' => []];
    }
}
