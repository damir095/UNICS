/**
 * Формальные признаки брака в задании ([[answer-judge-design]], раздел 2.1).
 *
 * Ярус не знает предмета и не обращается к сети: он ловит то, что видно по самой разметке
 * задания, и потому работает на любом предмете, где арифметический верификатор молчит.
 *
 * Разделение на «явный брак» и «подозрение» принципиально: по корреляционному признаку
 * выкашивать годные задания дороже, чем терпеть их. Подозрения уезжают в след и никогда
 * не меняют вердикт.
 *
 * @package local_unics
 */
class question_sanity {

    /** Во сколько раз ключ должен быть длиннее САМОГО ДЛИННОГО дистрактора для подозрения. */
    private const LONG_KEY_RATIO = 2.0;

    /**
     * Во сколько раз ключ должен быть длиннее СРЕДНЕГО дистрактора для подозрения.
     *
     * Второй признак нужен потому, что один многословный неверный вариант поднимает МАКСИМУМ и
     * прячет перекос: в зонде 2026-08-25 ключ 56 против 26/32/45 не ловился вовсе (45*2 = 90),
     * хотя вдвое длиннее среднего. Прежний довод «мерить по максимуму» при этом остается в силе -
     * признаки дополняют друг друга ([[long-key-hint-design]]).
     */
    private const LONG_KEY_AVG_RATIO = 1.6;

    /**
     * Минимальная АБСОЛЮТНАЯ разница в символах, без которой отношение ничего не значит.
     *
     * Без нее «Крокодил» (8) против «Кит»/«Еж»/«Лиса» (3/2/4) давало отношение 2.0 и подозрение
     * на пустом месте: прочесть четыре коротких слова легко, подсказки тут нет.
     *
     * Порог выбран замером по банку стенда, а не падением тестов: 293 вопроса дают 34 пометки
     * при нулевом зазоре, 27 при восьми и 22 при пятнадцати. На восьми отсекаются «Крокодил»
     * (зазор 4) и «часть целого» против «сумма» (7), но остаются настоящие перекосы вроде
     * «в провинции Шэньси» (18) против 8/8/7 (10) - там ключ вдвое длиннее и виден сразу.
     * Пятнадцать глушили и такие ([[long-key-hint-design]], раздел 7).
     */
    private const LONG_KEY_MIN_GAP = 8;

    /**
     * Отрицания в формулировке вопроса.
     *
     * Список намеренно шире одного «не»: «кроме» и «исключением» - то же самое отрицание,
     * выраженное иначе, и детям с ЗПР дается так же тяжело. Родственный список живет в
     * arithmetic_checker::NEGATIONS, но служит другому: там он ЗАПРЕЩАЕТ вердикт, здесь
     * лишь помечает вопрос для следа, поэтому классы не связаны.
     */
    private const NEGATION = '~(^|\s)не\s|неверн|не верн|ошибочн|ложн|(^|\s)кроме(\s|$)|исключен~u';

    /**
     * Вопрос требует НЕСКОЛЬКИХ ответов, а выбрать можно один.
     *
     * Живой заход 2026-08-23: «Какие два материка полностью расположены в южном полушарии?» с
     * одним верным вариантом. Ребенок, понимающий тему, ответить верно не может физически.
     *
     * Числительное обязательно («какие два», «три органоида»): голое множественное число -
     * законная форма вопроса с одним ответом («какие органоиды отвечают за фотосинтез»).
     */
    private const MULTI_ANSWER =
        // «выберите все», «отметьте всё» - букву «е» с точками не трогаем: в выходе ИИ она
        // сохраняется намеренно, и именно так модель чаще всего пишет «отметьте всё».
        '~(^|\s)(выберите|укажите|отметьте|назовите)\s+вс[её](\s|[.,!?:;]|$)'
        . '|(^|\s)перечислите(\s|[.,!?:;]|$)'
        // Числительное считается требованием нескольких ответов ТОЛЬКО после вопросительного
        // или побудительного слова. Иначе гибли счетные вопросы: «сколько будет два плюс три»,
        // «какое животное имеет три камеры сердца» (найдено ревью). Цифра наравне со словом -
        // «какие 2 материка» ломает ребенку задание ровно так же.
        . '|(^|\s)(каки[ехм]|назовите|выберите|укажите|отметьте)\s+'
        . '(\d+|два|две|три|четыре|пять)(\s|[.,!?:;]|$)~u';

    /** Длина вопроса, после которой формулировка тяжела для ребенка с ЗПР. */
    private const LONG_QUESTION = 150;

    /**
     * Нормализация для сравнения вариантов: пробелы, регистр, конечная точка.
     *
     * Кириллица - только через mb_*: strtolower ее не берет и два одинаковых варианта,
     * различающихся регистром, разошлись бы.
     */
    public static function normalize(string $s): string {
        // На битом UTF-8 preg_replace возвращает null: без страховки дальше уходил null в
        // mb_strtolower, и испорченный байтами вариант объявлялся ПУСТЫМ - вопрос выбывал
        // с неверной причиной. Тот же прием стоит в arithmetic_checker.
        $s = preg_replace('~\s+~u', ' ', trim($s)) ?? trim($s);
        $s = mb_strtolower($s);
        // Только точка и пробел: rtrim режет ПОБАЙТНО, и байт 0xA0 из списка обрубал бы
        // многобайтные символы, кончающиеся на него (эмодзи U+1F420, крестик U+2020),
        // оставляя невалидный UTF-8. Неразрывный пробел уже свернут в обычный выше.
        return rtrim($s, '. ');
    }

    /**
     * Нормализация варианта, НАЗВАННОГО моделью по тексту.
     *
     * Отличается от normalize() одним: срезает пронумерованную приставку. Модель, которую просят
     * назвать вариант дословно, нередко отвечает «2) Синий кит» - номер тут ее собственный, из
     * показанного ей списка, и в сопоставление идти не должен.
     *
     * Живет здесь, а не у судьи: тем же приемом ключ ищет генератор, когда просит у модели ТЕКСТ
     * верного ответа вместо номера. Две копии одного правила разъехались бы при первой правке -
     * ровно так проект уже обжегся на промте судьи, из-за чего и появилась PROMPT_MARKER.
     */
    public static function option_text(string $s): string {
        $stripped = preg_replace('~^\s*[0-9]{1,2}\s*[).]\s+~u', '', $s);
        return self::normalize($stripped ?? $s);
    }

    /**
     * Вердикт по формальным признакам.
     *
     * @param string $text текст вопроса
     * @param array $answers варианты ответа
     * @param int $correct индекс ключа
     * @return array ['verdict' => 'ok'|'drop', 'reason' => string, 'notes' => string[]]
     */
    public static function verdict(string $text, array $answers, int $correct): array {
        $answers = array_values($answers);
        $n = count($answers);
        $notes = [];

        if ($n < 2) {
            return self::drop('вариантов меньше двух');
        }
        if (self::normalize($text) === '') {
            // Вопрос без текста - тот же класс поломки разметки, что и пустой вариант.
            // Генератор такое отсеивает своей проверкой, но судья ее не делает.
            return self::drop('пустой текст вопроса');
        }
        if ($correct < 0 || $correct >= $n) {
            // Зажим индекса прятал ошибку: correct = 7 при четырех вариантах объявлял верным
            // последний, и ребенок получал «неверно» за верный ответ. Битый индекс означает,
            // что модель потеряла соответствие ключа вариантам, - доверять тут нечему.
            return self::drop('индекс ключа вне диапазона');
        }

        $norm = [];
        foreach ($answers as $a) {
            $one = self::normalize((string)$a);
            if ($one === '') {
                return self::drop('пустой вариант ответа');
            }
            $norm[] = $one;
        }
        if (count(array_unique($norm)) !== $n) {
            return self::drop('два варианта одинаковы');
        }
        $qnorm = self::normalize($text);
        if (in_array($qnorm, $norm, true)) {
            return self::drop('вариант повторяет текст вопроса');
        }
        if (preg_match(self::MULTI_ANSWER, $qnorm)) {
            return self::drop('вопрос требует несколько ответов, а выбрать можно один');
        }
        // Вариант, целиком входящий в другой, делает выбор неоднозначным: ребенок, знающий
        // ответ «Москва», не может решить между «Москва» и «Москва и область». Сравниваем ПО
        // СЛОВАМ, иначе «Рим» оказался бы вложен в «Кримпель».
        //
        // Сверяем ТОЛЬКО ключ против неверных вариантов: перекрытие двух дистракторов ребенку
        // не мешает - «Кит» и «Синий кит» при ключе «Акула» неоднозначности не создают.
        // Числа исключены: «10» - слово внутри «10 000», и правило выкашивало целые
        // арифметические комплекты (оба дефекта найдены ревью).
        foreach ($norm as $i => $other) {
            if ($i === $correct || self::both_numeric($norm[$correct], $other)) {
                continue;
            }
            if (self::contains_words($other, $norm[$correct])
                    || self::contains_words($norm[$correct], $other)) {
                return self::drop('один вариант входит в другой');
            }
        }

        // Длина верного ответа как подсказка ([[long-key-hint-design]]). Признаков ДВА, и они
        // дополняют друг друга, а не заменяют:
        //
        // - против САМОГО ДЛИННОГО дистрактора - грубый перекос. Ребенок видит подсказку с
        //   одного взгляда. Зонд 2026-08-25: ключ 63 против 14/27/16;
        // - против СРЕДНЕГО - умеренный. Один многословный неверный вариант поднимает максимум и
        //   прячет перекос: в том же зонде ключ 56 против 26/32/45 не ловился вовсе (45*2 = 90),
        //   хотя вдвое длиннее среднего. Тут ключ может быть длиннее по существу, поэтому вопрос
        //   принимаем, но педагог должен знать.
        //
        // Обратный перекос (короткий ключ среди длинных) подсказкой не считаем: привычки
        // «выбираю самый короткий» мы не наблюдали.
        $keylen = mb_strlen($norm[$correct]);
        $lens = [];
        foreach ($norm as $i => $one) {
            if ($i !== $correct) {
                $lens[] = mb_strlen($one);
            }
        }
        $longest = $lens ? max($lens) : 0;
        $avg = $lens ? array_sum($lens) / count($lens) : 0.0;

        // Зазор меряем ОТ ТОЙ ЖЕ величины, с которой сравниваем: для признака по среднему
        // разница с максимумом бывает мала (56 против 26/32/45 - всего 11 символов), а с
        // средним она и есть настоящая (21.7). Общий зазор от максимума отсекал бы главный
        // случай задачи.
        $by_max = $longest > 0
            && $keylen >= $longest * self::LONG_KEY_RATIO
            && $keylen - $longest >= self::LONG_KEY_MIN_GAP;
        $by_avg = $avg > 0
            && $keylen > $longest
            && $keylen >= $avg * self::LONG_KEY_AVG_RATIO
            && $keylen - $avg >= self::LONG_KEY_MIN_GAP;
        if ($by_max || $by_avg) {
            $notes[] = 'ключ заметно длиннее прочих вариантов';
        }
        foreach ($norm as $one) {
            if (preg_match('~все перечислен|все ответы верн|все варианты верн~u', $one)) {
                $notes[] = 'среди вариантов «все перечисленное»';
                break;
            }
        }
        // Отрицание детям с ЗПР дается тяжело, но само по себе задание не портит.
        $lower = mb_strtolower($text);
        if (preg_match(self::NEGATION, $lower)) {
            $notes[] = 'отрицание в формулировке';
        }
        // Несколько отрицаний в одном вопросе разбирать тяжело всем, ребенку с ЗПР - вдвойне.
        // Считаем именно СЛОВО «не» через границы без съедания соседних символов: со шаблоном
        // «(^|\s)не\s» подряд идущее «не не» давало одно совпадение вместо двух.
        if (preg_match_all('~(?<!\p{L})не(?!\p{L})~u', $lower) > 1) {
            $notes[] = 'несколько отрицаний в вопросе';
        }
        if (mb_strlen(trim($text)) > self::LONG_QUESTION) {
            $notes[] = 'вопрос длинный - тяжело для ЗПР';
        }
        // Несколько предложений в вопросе: ребенку приходится удерживать в голове условие и
        // сам вопрос одновременно. Двух букв перед точкой достаточно, чтобы не считать
        // предложением инициалы («А. С. Пушкин»).
        if (preg_match_all('~\p{L}{2,}[.!?]\s+\p{Lu}~u', trim($text)) > 0) {
            $notes[] = 'вопрос из нескольких предложений';
        }

        return ['verdict' => 'ok', 'reason' => '', 'notes' => $notes];
    }

    /**
     * Входит ли строка $needle в $haystack как ЦЕЛЫЕ слова подряд.
     *
     * По подстроке сравнивать нельзя: «Рим» оказался бы вложен в «Кримпель», и годное задание
     * выбывало бы за неоднозначность, которой нет.
     */
    private static function contains_words(string $haystack, string $needle): bool {
        if ($needle === '' || $haystack === $needle) {
            return false;
        }
        // Режем и по пунктуации: «Москва,» и «Москва» - одно слово, а не два разных,
        // и без этого неоднозначная пара проходила мимо.
        $hw = preg_split('~[\s,;:.!?()]+~u', $haystack, -1, PREG_SPLIT_NO_EMPTY) ?: [];
        $nw = preg_split('~[\s,;:.!?()]+~u', $needle, -1, PREG_SPLIT_NO_EMPTY) ?: [];
        $n = count($nw);
        if ($n === 0 || $n > count($hw)) {
            return false;
        }
        for ($i = 0; $i + $n <= count($hw); $i++) {
            if (array_slice($hw, $i, $n) === $nw) {
                return true;
            }
        }
        return false;
    }

    /**
     * Оба варианта - числа (в том числе с разрядами и дробью).
     *
     * У чисел вложенность слов ничего не значит: «10» стоит внутри «10 000», а это два разных
     * ответа. Без исключения правило выкашивало целые арифметические комплекты.
     */
    private static function both_numeric(string $a, string $b): bool {
        $num = '~^-?[\d\s.,/]+$~u';
        return preg_match($num, $a) === 1 && preg_match($num, $b) === 1;
    }

    private static function drop(string $reason): array {
        return ['verdict' => 'drop', 'reason' => $reason, 'notes' => []];
    }
}
